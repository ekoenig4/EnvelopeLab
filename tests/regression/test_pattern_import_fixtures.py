def test_special_shape_rest_model_carries_ease_and_tags(
    special: BuildPackResult, tmp_path: Path
) -> None:
    assert special.rest_model is not None
    path = save_rest_model(special.rest_model, tmp_path / "rest.json")
    data = load_rest_model(path)
    seams = {s["id"]: s for s in data["seams"]}
    assert seams["tube_base"]["designed_ease_m"] == pytest.approx(0.040)
    assert seams["tube_base"]["type"] == "appendage"
    assert seams["body:v:1/2:A"]["load_tape"] == "25 mm load tape"
    assert any(k.endswith(":tape0") for k in data["tape_paths"])
    zones = {i["id"]: i["material_zone"] for i in data["instances"]}
    assert zones["tube"] == "appendage"
    grains = {i["id"]: i["grain"] for i in data["instances"]}
    assert grains["body/B@1"] == pytest.approx([1.0, 0.0])
    assert "not an inflated or solved shape" in data["status"]
    assert data["metadata"]["design_content_hash"] == special.imported.content_hash
    positions = np.array(data["nodes"]["initial_positions"])
    assert positions.shape == (special.rest_model.mesh.n_nodes, 3)
    assert np.all(np.isfinite(positions))


def test_reports_are_written(special: BuildPackResult, tmp_path: Path) -> None:
    files = write_reports(special, tmp_path)
    expected = {
        "panel-inventory.csv",
        "panel-inventory.json",
        "panel-inventory.html",
        "seam-audit.csv",
        "seam-audit.json",
        "seam-audit.html",
        "seam-graph.csv",
        "seam-graph.json",
        "mesh-report.json",
        "mesh-report.html",
        "import-warnings.json",
        "import-warnings.csv",
        "import-warnings.html",
        "rest-model.json",
        "index.html",
    }
    assert {p.name for p in files.values()} == expected
    inventory = json.loads((tmp_path / "panel-inventory.json").read_text(encoding="utf-8"))
    tube = next(r for r in inventory if r["piece_id"] == "TUBE")
    assert tube["assembled"] == 1 and tube["kind"] == "appendage"
    assert tube["finished_area_m2"] < tube["cut_area_m2"]
    assert "Status: PASS" in (tmp_path / "index.html").read_text(encoding="utf-8")


