def test_standard_gore_has_exactly_mouth_and_crown_loops(standard: BuildPackResult) -> None:
    report = standard.mesh_report
    assert report is not None
    assert sorted(loop.opening or "?" for loop in report.boundary_loops) == ["crown", "mouth"]
    assert report.passed, report.checks
    assert report.components == 1
    assert report.edges_nonmanifold == 0
    assert report.euler_characteristic == 0  # a sphere with two holes
    assert abs(report.area_relative_error) <= 0.005
    loops = {loop.opening: loop.rest_length for loop in report.boundary_loops}
    ring = standard.spec.rings[0]
    bottom = standard.pieces[ring.rows[0]]
    assert loops["mouth"] == pytest.approx(
        ring.gore_count * standard.assembly.instances["body/A@1"].edges["bottom"].length, rel=1e-9
    )
    assert bottom.valid


def test_standard_gore_audit_is_clean(standard: BuildPackResult) -> None:
    assert standard.audit.error_count == 0
    assert max(r.abs_mismatch for r in standard.audit.rows) < 1e-4
    assert standard.status == "PASS"


def test_cut_only_import_matches_sew_lines(standard: BuildPackResult) -> None:
    cut_only = import_build_pack(FIXTURES / "standard_gore" / "build-pack-cut-only.yaml")
    for pid, piece in standard.pieces.items():
        other = cut_only.pieces[pid]
        assert other.outline_source == "inset"
        assert np.max(distance_to_polyline(piece.outline, other.outline, True)) < 5e-4
        assert other.finished_area == pytest.approx(piece.finished_area, rel=1e-4)
    assert cut_only.mesh_report is not None and cut_only.mesh_report.passed


def test_special_shape_appendage_seam_with_designed_ease(special: BuildPackResult) -> None:
    graph = special.assembly.graph
    base = next(s for s in graph.seams if s.seam_id == "tube_base")
    assert base.seam_type == "appendage"
    assert base.props.designed_ease_m == pytest.approx(0.040)
    row = next(r for r in special.audit.rows if r.seam_id == "tube_base")
    assert row.severity == "info"
    assert row.length_b - row.length_a == pytest.approx(0.040, abs=2e-4)
    assert row.abs_mismatch < 1e-3
    assert special.audit.error_count == 0


