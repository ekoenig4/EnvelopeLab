@pytest.mark.slow
def test_alien_matches_golden_summary(alien: BuildPackResult) -> None:
    golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
    pieces = {pid: p for pid, p in alien.pieces.items()}
    assert sorted(pieces) == sorted(golden["pieces"])
    for pid, expected in golden["pieces"].items():
        piece = pieces[pid]
        assert piece.quantity == expected["quantity"], pid
        assert piece.finished_area == pytest.approx(expected["finished_area_m2"], abs=1e-6), pid
        assert piece.cut_area == pytest.approx(expected["cut_area_m2"], abs=1e-6), pid
    assert len(alien.audit.rows) == golden["seams"]
    assert alien.mesh_report is not None
    openings = sorted(loop.opening or "?" for loop in alien.mesh_report.boundary_loops)
    assert openings == golden["openings"]
    eye = next(r for r in alien.audit.rows if r.seam_id == "eye_rim_left")
    assert eye.severity == "info"
    assert eye.designed_ease == pytest.approx(1.240)


def test_no_design_specific_code() -> None:
    """The library must not special-case any fixture (AGENTS.md hard rule).

    ``validation/pattern_import.py`` is exempt: it lists the fixture files and writes the
    validation page text about them; it contains no engineering logic.
    """
    # Material names such as Nomex are library data, not design special cases.
    pattern = re.compile(r"alien|antenna|eye[_ ]?pod", re.IGNORECASE)
    exempt = ROOT / "src" / "envelopelab" / "validation" / "pattern_import.py"
    offenders = [
        str(path.relative_to(ROOT))
        for path in (ROOT / "src").rglob("*.py")
        if path != exempt and pattern.search(path.read_text(encoding="utf-8"))
    ]
    assert not offenders


@pytest.mark.slow
def test_generated_page_is_current() -> None:
    summaries = run_fixtures(fixture_paths(ROOT))
    assert all(s.passed for s in summaries), [s.name for s in summaries if not s.passed]
    assert PAGE.read_text(encoding="utf-8") == render_markdown(summaries), (
        "docs/validation/pattern-import-fixtures.md is stale; "
        "run python scripts/generate_validation_docs.py"
    )
